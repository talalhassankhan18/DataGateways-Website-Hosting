#!/usr/bin/env node
/**
 * Builds docs/PLACEHOLDERS.md — the register of every unverified claim on the site.
 *
 * Nothing marked [PLACEHOLDER] or [CONFIRM] in docs/copy-deck.md may ship as written: the numbers
 * are invented to fill the layout and the compliance marks are unearned until the certificate
 * exists. Publishing an unearned certification mark is a legal problem, not a copy problem, so the
 * register has to be mechanical rather than a list someone keeps by hand.
 *
 * Source of truth is the content modules themselves, scanned for `flag.placeholder(...)` and
 * `flag.confirm(...)`, so an entry cannot be added to the site without appearing here.
 *
 * Run with `npm run docs:placeholders`, and `--check` in CI to fail when the file is stale.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'apps', 'web', 'src', 'content');
const outFile = join(root, 'docs', 'PLACEHOLDERS.md');

const check = process.argv.includes('--check');

/**
 * Reads a single-quoted JS string literal starting at `from`, honouring backslash escapes.
 * Returns the decoded text and the index just past the closing quote, or null when `from` is not
 * sitting on a quote.
 */
const readString = (source, from) => {
  let i = from;
  while (i < source.length && /\s/.test(source[i])) i += 1;
  if (source[i] !== "'") return null;

  let out = '';
  i += 1;
  while (i < source.length) {
    const char = source[i];
    if (char === '\\') {
      out += source[i + 1];
      i += 2;
      continue;
    }
    if (char === "'") return { text: out, end: i + 1 };
    out += char;
    i += 1;
  }
  return null;
};

const entries = [];

for (const file of (await readdir(contentDir)).filter((name) => name.endsWith('.ts')).sort()) {
  const path = join(contentDir, file);
  const source = await readFile(path, 'utf8');

  for (const match of source.matchAll(/flag\.(placeholder|confirm)\(/g)) {
    const status = match[1];
    const open = match.index + match[0].length;

    const value = readString(source, open);
    // The value is occasionally an expression rather than a literal (an array of tiles, say);
    // those still belong in the register, just without a quotable value.
    const note = value ? readString(source, value.end + (source[value.end] === ',' ? 1 : 0)) : null;

    entries.push({
      file: relative(root, path).replace(/\\/g, '/'),
      line: source.slice(0, match.index).split('\n').length,
      status,
      value: value ? value.text : '(non-literal — see source)',
      note: note ? note.text : '',
    });
  }
}

const placeholders = entries.filter((entry) => entry.status === 'placeholder');
const confirms = entries.filter((entry) => entry.status === 'confirm');

const table = (rows) =>
  rows.length === 0
    ? '_None._\n'
    : [
        '| Value | Where | Who supplies it |',
        '| --- | --- | --- |',
        ...rows.map(
          (row) =>
            `| \`${row.value.replace(/\|/g, '\\|')}\` | [${row.file}:${row.line}](../${row.file}#L${row.line}) | ${
              row.note.replace(/\|/g, '\\|') || '—'
            } |`,
        ),
      ].join('\n') + '\n';

const markdown = `# Placeholder register — DataGateways

<!-- Generated by scripts/generate-placeholders.mjs. Do not edit by hand — run \`npm run docs:placeholders\`. -->

Every value still carrying a \`flag.placeholder()\` or \`flag.confirm()\` marker in
\`apps/web/src/content\`. **None of it ships as written.**

In development each of these renders inside a dashed accent outline with a \`PLACEHOLDER\` or
\`CONFIRM\` tag (see \`apps/web/src/components/primitives/PlaceholderBadge.tsx\`); the badge is
compiled out of the production bundle, which is exactly why this register exists.

> **This file only reports what is still *marked*.** Content that has been written out as a
> realistic draft no longer carries a marker and therefore does not appear here — but it is still
> the client's to confirm. That list is
> [\`PRE-LAUNCH-SIGNOFF.md\`](PRE-LAUNCH-SIGNOFF.md), and it is maintained by hand.
> An empty register below means "nothing is flagged in code", not "everything is verified".

| | Count |
| --- | --- |
| \`[PLACEHOLDER]\` — invented to fill the layout | ${placeholders.length} |
| \`[CONFIRM]\` — factual claim only the client can stand behind | ${confirms.length} |
| **Total** | **${entries.length}** |

## [PLACEHOLDER] — invented values

Numbers and dates with nothing behind them. They exist so the layout can be reviewed at the right
length. Shipping one is publishing a claim the client cannot stand behind.

${table(placeholders)}
## [CONFIRM] — claims needing the client's word

Product capabilities, routed mailboxes and compliance marks. Every framework named on this site —
SOC 2, ISO 27001, GDPR, HIPAA, the EU AI Act — is a draft assumption until the certificate or
completed assessment exists.

${table(confirms)}
## Before launch

- [ ] Replace all ${placeholders.length} \`[PLACEHOLDER]\` values with client-supplied facts, or cut the section.
- [ ] Get written sign-off on all ${confirms.length} \`[CONFIRM]\` claims from the client's product and legal teams.
- [ ] Work through [\`PRE-LAUNCH-SIGNOFF.md\`](PRE-LAUNCH-SIGNOFF.md), which covers the drafted
      content that no longer carries a marker — compliance marks, metrics, integration lists,
      mailboxes, the registered address and the partner directory.
`;

if (check) {
  const current = await readFile(outFile, 'utf8').catch(() => null);
  if (current !== markdown) {
    console.error(
      'placeholders: docs/PLACEHOLDERS.md is out of date — run `npm run docs:placeholders` and commit the result.',
    );
    process.exit(1);
  }
  console.log(`placeholders: register is up to date (${entries.length} entries)`);
} else {
  await writeFile(outFile, markdown, 'utf8');
  console.log(
    `placeholders: ${entries.length} entries written to docs/PLACEHOLDERS.md ` +
      `(${placeholders.length} placeholder, ${confirms.length} confirm)`,
  );
}
